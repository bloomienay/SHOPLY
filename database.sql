create or replace function public.shoply_track_transaction_cancellation()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if tg_op = 'UPDATE' and old.order_status = 'Dibatalkan'
      and new.order_status is distinct from old.order_status then
    raise exception 'Pesanan yang sudah dibatalkan tidak dapat diaktifkan kembali.';
  end if;
  if new.order_status = 'Dibatalkan' then
    if tg_op = 'INSERT' or old.order_status is distinct from new.order_status then
      new.cancelled_at := current_date;
      if tg_op = 'UPDATE' then
        new.cancellation_review_required := old.order_status in ('Dikirim / dalam penyelesaian', 'Selesai');
      else
        new.cancellation_review_required := true;
      end if;
    end if;
  else
    new.cancelled_at := null;
    new.cancellation_review_required := false;
  end if;
  return new;
end;
$$;

drop trigger if exists shoply_track_transaction_cancellation on public.transactions;
create trigger shoply_track_transaction_cancellation
  before insert or update on public.transactions
  for each row execute function public.shoply_track_transaction_cancellation();


insert into public.transactions (customer_id, transaction_date, payment_status, service_fee, amount_paid, notes)
select id, current_date, 'Lunas', 150000, 500000, 'Contoh transaksi lunas'
from public.customers
where email = 'alya@example.com'
  and not exists (
    select 1 from public.transactions t
    where t.customer_id = public.customers.id and t.notes = 'Contoh transaksi lunas'
  );

update public.transactions t
set details = jsonb_build_array(jsonb_build_object(
  'id', -1,
  'service_id', s.id,
  'quantity', 1,
  'unit_price', s.price,
  'subtotal', s.price
))
from public.customers c, public.services s
where t.customer_id = c.id
  and c.email = 'alya@example.com'
  and t.notes = 'Contoh transaksi lunas'
  and s.name = 'Kemeja Linen'
  and t.details = '[]'::jsonb;
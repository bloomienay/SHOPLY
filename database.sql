create or replace function public.shoply_sync_transaction_payment()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  detail jsonb;
  detail_count integer := 0;
  detail_quantity numeric;
  detail_price numeric;
  detail_service_id bigint;
  detail_subtotal numeric;
  detail_service_name text;
  detail_brand text;
  detail_category text;
  prior_detail jsonb;
  preserve_detail_snapshot boolean;
  normalized_detail jsonb;
  payment jsonb;
  payment_id text;
  payment_date date;
  payment_amount numeric;
  paid_total numeric := 0;
  normalized_payments jsonb := '[]'::jsonb;
  preserve_legacy_details boolean := false;
  normalized_details jsonb := '[]'::jsonb;
  total_due numeric := coalesce(new.service_fee, 0);
begin
  if tg_op = 'UPDATE' and old.order_status = 'Selesai'
      and new.order_status not in ('Selesai', 'Dibatalkan') then
    raise exception 'Pesanan selesai tidak dapat dikembalikan ke status sebelumnya.';
  end if;
  if tg_op = 'UPDATE' and old.order_status = 'Dibatalkan'
      and (new.payments is distinct from old.payments
        or new.details is distinct from old.details
        or new.amount_paid is distinct from old.amount_paid
        or new.service_fee is distinct from old.service_fee) then
    raise exception 'Rincian dan pembayaran pesanan yang sudah dibatalkan tidak dapat diubah.';
  end if;
  if tg_op = 'UPDATE' and old.order_status = 'Selesai'
      and (new.customer_id is distinct from old.customer_id
        or new.transaction_date is distinct from old.transaction_date
        or new.service_fee is distinct from old.service_fee
        or new.payment_policy is distinct from old.payment_policy
        or new.details is distinct from old.details) then
    raise exception 'Pesanan selesai tidak dapat mengubah pelanggan, tanggal, biaya, atau rincian. Buat catatan koreksi terpisah.';
  end if;
  if tg_op = 'UPDATE'
      and new.order_status is distinct from old.order_status
      and new.user_id is not distinct from old.user_id
      and new.customer_id is not distinct from old.customer_id
      and new.transaction_date is not distinct from old.transaction_date
      and new.service_fee is not distinct from old.service_fee
      and new.amount_paid is not distinct from old.amount_paid
      and new.payment_status is not distinct from old.payment_status
      and new.payments is not distinct from old.payments
      and new.details is not distinct from old.details then
    if new.payment_policy = 'full_before_shipping'
        and new.order_status = 'Dikirim / dalam penyelesaian' then
      select coalesce(new.service_fee, 0) + coalesce(sum(
        (detail.value ->> 'quantity')::numeric * (detail.value ->> 'unit_price')::numeric
      ), 0)
      into total_due
      from jsonb_array_elements(new.details) as detail(value);
      if coalesce(new.amount_paid, 0) < total_due then
        raise exception 'Pesanan harus lunas sebelum status dikirim.';
      end if;
    end if;
    return new;
  end if;
  if new.payment_policy not in ('flexible', 'full_before_shipping') then
    raise exception 'Ketentuan pembayaran transaksi tidak valid.';
  end if;
  if new.service_fee::text in ('NaN', 'Infinity', '-Infinity')
      or new.amount_paid::text in ('NaN', 'Infinity', '-Infinity')
      or new.service_fee < 0 or new.amount_paid < 0 then
    raise exception 'Biaya jasa dan jumlah dibayar harus berupa angka terbatas yang tidak negatif.';
  end if;
  if jsonb_typeof(new.details) is distinct from 'array' then
    raise exception 'Rincian transaksi harus berupa daftar.';
  end if;
  if jsonb_typeof(new.payments) is distinct from 'array' then
    raise exception 'Pembayaran transaksi harus berupa daftar.';
  end if;
  if tg_op = 'UPDATE' then
    preserve_legacy_details := new.details = old.details;
  end if;

  for detail in select value from jsonb_array_elements(new.details)
  loop
    detail_count := detail_count + 1;
    if detail_count > 500 or jsonb_typeof(detail) <> 'object' then
      raise exception 'Rincian transaksi tidak valid atau melebihi 500 baris.';
    end if;
    begin
      detail_quantity := (detail ->> 'quantity')::numeric;
      detail_price := (detail ->> 'unit_price')::numeric;
      detail_service_id := (detail ->> 'service_id')::bigint;
    exception when others then
      raise exception 'Setiap rincian wajib memiliki produk, kuantitas, dan harga yang valid.';
    end;
    if detail_service_id is null or detail_service_id <= 0 or detail_quantity is null or detail_price is null
        or detail_quantity < 1 or detail_quantity > 1000000 or detail_quantity <> trunc(detail_quantity)
        or detail_price < 0 or detail_price > 9999999999.99
        or detail_quantity::text in ('NaN', 'Infinity', '-Infinity')
        or detail_price::text in ('NaN', 'Infinity', '-Infinity') then
      raise exception 'Kuantitas harus bilangan bulat positif dan harga tidak boleh negatif.';
    end if;
    prior_detail := null;
    preserve_detail_snapshot := false;
    if tg_op = 'UPDATE' then
      select old_detail.value into prior_detail
      from jsonb_array_elements(old.details) as old_detail(value)
      where old_detail.value ->> 'id' = detail ->> 'id'
      limit 1;
      preserve_detail_snapshot := prior_detail is not null
        and prior_detail ->> 'service_id' = detail ->> 'service_id';
    end if;
    select service.name, service.brand, service.category into detail_service_name, detail_brand, detail_category
    from public.services service
    where service.id = detail_service_id
      and (service.user_id is null or service.user_id = new.user_id);
    if not found then
      if not preserve_legacy_details and not preserve_detail_snapshot then
        raise exception 'Produk pada rincian tidak tersedia di workspace ini.';
      end if;
      detail_service_name := coalesce(detail ->> 'service_name', 'Produk terdahulu');
      detail_brand := coalesce(detail ->> 'brand', '');
      detail_category := case when detail ->> 'category' in ('Jasa', 'Produk')
        then detail ->> 'category' else 'Produk' end;
    end if;
    if preserve_detail_snapshot then
      if prior_detail ->> 'category' in ('Jasa', 'Produk') then
        detail_category := prior_detail ->> 'category';
      end if;
      detail_service_name := coalesce(nullif(prior_detail ->> 'service_name', ''), detail_service_name);
      detail_brand := coalesce(nullif(prior_detail ->> 'brand', ''), detail_brand, '');
    end if;
    detail_subtotal := round(detail_quantity * detail_price, 2);
    total_due := total_due + detail_subtotal;
    normalized_detail := jsonb_set(detail, '{subtotal}', to_jsonb(detail_subtotal), true);
    normalized_detail := jsonb_set(normalized_detail, '{category}', to_jsonb(detail_category), true);
    if detail_service_name is not null then
      normalized_detail := jsonb_set(normalized_detail, '{service_name}', to_jsonb(detail_service_name), true);
    end if;
    normalized_detail := jsonb_set(normalized_detail, '{brand}', to_jsonb(coalesce(detail_brand, '')), true);
    normalized_details := normalized_details || jsonb_build_array(normalized_detail);
  end loop;

  detail_count := 0;
  for payment in select value from jsonb_array_elements(new.payments)
  loop
    detail_count := detail_count + 1;
    if detail_count > 500 or jsonb_typeof(payment) <> 'object' then
      raise exception 'Daftar pembayaran tidak valid atau melebihi 500 baris.';
    end if;
    begin
      payment_id := payment ->> 'id';
      payment_date := (payment ->> 'payment_date')::date;
      payment_amount := (payment ->> 'amount')::numeric;
    exception when others then
      raise exception 'Setiap pembayaran wajib memiliki ID, tanggal, dan jumlah yang valid.';
    end;
    if nullif(btrim(payment_id), '') is null or payment_date is null
        or payment_amount is null or payment_amount <= 0 or payment_amount > 9999999999.99
        or payment_amount::text in ('NaN', 'Infinity', '-Infinity') then
      raise exception 'Setiap pembayaran harus memiliki tanggal dan jumlah positif yang valid.';
    end if;
    if exists (
      select 1 from jsonb_array_elements(normalized_payments) as existing_payment(value)
      where existing_payment.value ->> 'id' = payment_id
    ) then
      raise exception 'ID pembayaran harus unik dalam satu transaksi.';
    end if;
    payment_amount := round(payment_amount, 2);
    paid_total := paid_total + payment_amount;
    normalized_payments := normalized_payments || jsonb_build_array(jsonb_build_object(
      'id', payment_id, 'payment_date', payment_date, 'amount', payment_amount
    ));
  end loop;

  new.details := normalized_details;
  new.payments := normalized_payments;
  new.amount_paid := paid_total;
  new.payment_status := case
    when total_due <= 0 and paid_total > 0 then 'Lunas'
    when total_due <= 0 or paid_total <= 0 then 'Belum dibayar'
    when paid_total < total_due then 'Sebagian'
    else 'Lunas'
  end;
  if new.payment_policy = 'full_before_shipping'
      and new.order_status = 'Dikirim / dalam penyelesaian'
      and paid_total < total_due then
    raise exception 'Pesanan harus lunas sebelum status dikirim.';
  end if;
  return new;
end;
$$;


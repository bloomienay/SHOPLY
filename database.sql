create table if not exists public.customers (
  id bigint generated by default as identity primary key,
  full_name text not null,
  phone text,
  email text,
  address text,
  created_at timestamptz not null default now(),
  constraint customers_email_unique unique (email)
);

create table if not exists public.services (
  id bigint generated by default as identity primary key,
  name text not null unique,
  category text not null check (category in ('Jasa', 'Produk')),
  brand text,
  product_type text check (product_type in ('Sepatu', 'Tas', 'Pakaian', 'Aksesori', 'Lainnya')),
  image_url text,
  description text,
  price numeric(12, 2) not null default 0 check (price >= 0),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.services add column if not exists brand text;
alter table public.services add column if not exists product_type text;
alter table public.services add column if not exists image_url text;

create table if not exists public.transactions (
  id bigint generated by default as identity primary key,
  customer_id bigint not null references public.customers(id) on update cascade on delete restrict,
  transaction_date date not null default current_date,
  payment_status text not null default 'Belum dibayar'
    check (payment_status in ('Belum dibayar', 'Sebagian', 'Lunas')),
  service_fee numeric(12, 2) not null default 0 check (service_fee >= 0),
  amount_paid numeric(12, 2) not null default 0 check (amount_paid >= 0),
  notes text,
  details jsonb not null default '[]'::jsonb check (jsonb_typeof(details) = 'array'),
  created_at timestamptz not null default now()
);

alter table public.transactions add column if not exists details jsonb not null default '[]'::jsonb;

create table if not exists public.finance_records (
  id bigint generated by default as identity primary key,
  record_type text not null check (record_type in ('account', 'journal')),
  account_code text,
  account_name text,
  account_type text check (account_type in ('Aset', 'Liabilitas', 'Modal', 'Pendapatan', 'Beban')),
  entry_date date,
  reference text,
  description text,
  lines jsonb not null default '[]'::jsonb check (jsonb_typeof(lines) = 'array'),
  created_at timestamptz not null default now(),
  constraint finance_records_account_unique unique (record_type, account_code),
  constraint finance_records_reference_unique unique (reference),
  constraint finance_records_shape check (
    (record_type = 'account' and account_code is not null and account_name is not null and account_type is not null and reference is null)
    or (record_type = 'journal' and entry_date is not null and reference is not null and description is not null)
  )
);

-- Copy legacy rows before removing the old tables, so rerunning this script keeps existing data.
do $$
begin
  if to_regclass('public.transaction_details') is not null then
    update public.transactions t
    set details = coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', d.id,
        'service_id', d.service_id,
        'quantity', d.quantity,
        'unit_price', d.unit_price,
        'subtotal', d.subtotal
      ) order by d.id)
      from public.transaction_details d
      where d.transaction_id = t.id
    ), '[]'::jsonb)
    where t.details = '[]'::jsonb;
  end if;

  if to_regclass('public.accounts') is not null then
    insert into public.finance_records (record_type, account_code, account_name, account_type)
    select 'account', code, name, account_type from public.accounts
    on conflict (record_type, account_code) do nothing;
  end if;

  if to_regclass('public.journal_entries') is not null and to_regclass('public.journal_lines') is not null then
    insert into public.finance_records (record_type, entry_date, reference, description, lines)
    select 'journal', e.entry_date, e.reference, e.description, coalesce(
      jsonb_agg(jsonb_build_object(
        'account_code', a.code,
        'account_name', a.name,
        'account_type', a.account_type,
        'description', l.description,
        'debit', l.debit,
        'credit', l.credit
      ) order by l.id) filter (where l.id is not null), '[]'::jsonb
    )
    from public.journal_entries e
    left join public.journal_lines l on l.journal_entry_id = e.id
    left join public.accounts a on a.id = l.account_id
    group by e.id
    on conflict (reference) do nothing;
  end if;
end $$;


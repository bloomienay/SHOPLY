create or replace function public.shoply_validate_finance_journal()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  line jsonb;
  line_count integer := 0;
  debit_total numeric := 0;
  credit_total numeric := 0;
  line_debit numeric;
  line_credit numeric;
  account_found boolean;
begin
  if new.record_type <> 'journal' then
    return new;
  end if;
  if jsonb_typeof(new.lines) is distinct from 'array' then
    raise exception 'Baris jurnal harus berupa daftar.';
  end if;
  for line in select value from jsonb_array_elements(new.lines)
  loop
    line_count := line_count + 1;
    if line_count > 500 then
      raise exception 'Jurnal tidak boleh melebihi 500 baris.';
    end if;
    begin
      line_debit := coalesce((line ->> 'debit')::numeric, 0);
      line_credit := coalesce((line ->> 'credit')::numeric, 0);
    exception when others then
      raise exception 'Nilai debit dan kredit harus berupa angka.';
    end;
    if line_debit::text in ('NaN', 'Infinity', '-Infinity')
        or line_credit::text in ('NaN', 'Infinity', '-Infinity')
        or line_debit < 0 or line_credit < 0 or (line_debit > 0 and line_credit > 0) then
      raise exception 'Setiap baris jurnal hanya boleh memiliki debit atau kredit positif.';
    end if;
    if line_debit = 0 and line_credit = 0 then
      raise exception 'Baris jurnal tidak boleh bernilai nol.';
    end if;
    select exists (
      select 1 from public.finance_records account
      where account.record_type = 'account'
        and account.account_code = line ->> 'account_code'
        and account.user_id is null
    ) into account_found;
    if not account_found then
      raise exception 'Kode akun jurnal tidak ditemukan di bagan akun.';
    end if;
    debit_total := debit_total + line_debit;
    credit_total := credit_total + line_credit;
  end loop;
  if line_count < 2 or debit_total <= 0 or debit_total <> credit_total then
    raise exception 'Jurnal wajib memiliki minimal dua baris dan total debit harus sama dengan kredit.';
  end if;
  if nullif(btrim(new.description), '') is null then
    raise exception 'Keterangan jurnal wajib diisi.';
  end if;
  return new;
end;
$$;

